SELECT
    C.NOME,
    P.ID_PEDIDO,
    PR.PRODUTO
FROM CLIENTES C
INNER JOIN PEDIDOS P
ON C.ID_CLIENTE = P.ID_CLIENTE
INNER JOIN PRODUTOS PR
ON P.ID_PRODUTO = PR.ID_PRODUTO;

SELECT
    C.NOME,
    COUNT(*) AS TOTAL_PEDIDOS
FROM CLIENTES C
INNER JOIN PEDIDOS P
ON C.ID_CLIENTE = P.ID_CLIENTE
GROUP BY C.NOME;